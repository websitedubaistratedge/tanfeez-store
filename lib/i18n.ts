export type TKey = { [S in Sections]: `${S}.${keyof Dict[S] & string}` }[Sections];

export function t(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  const [s, k] = key.split(".") as [Sections, string];
  const entry = (dict[s] as Record<string, readonly [string, string]>)[k];
  let out = entry ? entry[lang === "ar" ? 1 : 0] : key;
  if (vars) for (const [vk, vv] of Object.entries(vars)) out = out.replace(`{${vk}}`, String(vv));
  return out;
}

export const tx = (v: L10n | undefined, lang: Lang) => (v ? v[lang] || v.en : "");

export function money(n: number, lang: Lang = "en") {
  const s = Math.round(n).toLocaleString("en-US");
  return lang === "ar" ? `${s} د.إ` : `AED ${s}`;
}

